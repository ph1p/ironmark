// Builds the slim npm subpath entries (`ironmark/html`, `ironmark/mdx`, `ironmark/ast`).
// Each one gets its own WASM binary compiled with only the features it calls, plus a
// generated Node entry (sync, file-backed) and browser entry (async `init()`).
// The full `ironmark` entry is built by `pnpm build:wasm` + `wasm/build.mjs`.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { delimiter, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Exports each subpath offers, mapped to the shared.js factory and wasm-bindgen functions. */
const FACTORIES = {
  markdownToHtml: ["createMarkdownToHtml", "parse", "parseDefault"],
  mdxToJsx: ["createMdxToJsx", "renderJsx"],
  markdownToAst: ["createMarkdownToAst", "parseToAst"],
  astToMarkdown: ["createAstToMarkdown", "renderMarkdown"],
};

/** Constants every entry re-exports from shared.js. */
const COMMON_HELPERS = ["DEFAULT_OPTIONS", "PRESETS"];

const ENTRIES = [
  { name: "html", features: "html-only", exports: ["markdownToHtml"], formats: ["html"] },
  {
    name: "mdx",
    features: "mdx",
    exports: ["mdxToJsx", "markdownToHtml"],
    formats: ["html", "jsx"],
  },
  {
    name: "ast",
    features: "ast",
    exports: ["markdownToAst", "astToMarkdown", "markdownToHtml"],
    formats: ["html", "ast", "markdown"],
    helpers: ["AST_SCHEMA_VERSION", "extractHeadings", "summarizeAst"],
  },
];

const dir = dirname(fileURLToPath(import.meta.url));
const root = dirname(dir);
const env = {
  ...process.env,
  PATH: [join(root, ".wasm-tools/bin"), join(homedir(), ".cargo/bin"), process.env.PATH]
    .filter(Boolean)
    .join(delimiter),
};

function run(command, args, capture = false) {
  const result = spawnSync(command, args, {
    cwd: root,
    env,
    encoding: "utf8",
    stdio: capture ? "pipe" : "inherit",
  });
  if (result.error) throw new Error(`Cannot run ${command}`, { cause: result.error });
  if (result.status !== 0) {
    throw new Error(
      `${command} ${args.join(" ")} failed (exit ${result.status}): ${result.stderr ?? ""}`,
    );
  }
  return result.stdout?.trim();
}

function entrySources({ name, exports, formats, helpers: extraHelpers = [] }) {
  const helpers = [...COMMON_HELPERS, ...extraHelpers];
  const glue = `./pkg-${name}/ironmark_${name}_bg.js`;
  const asset = `./pkg-${name}/ironmark_${name}_bg.wasm`;
  const glueImport = `./ironmark_${name}_bg.js`;
  const factories = [...new Set(exports.map((e) => FACTORIES[e][0]))];
  const header = `// Generated by wasm/build-entries.mjs — do not edit\n`;
  const body =
    exports
      .map((e) => {
        const [factory, ...fns] = FACTORIES[e];
        return `export const ${e} = ${factory}(${fns.map((f) => `wasmGlue.${f}`).join(", ")});`;
      })
      .join("\n") +
    `\n\nexport const CAPABILITIES = createCapabilities(${JSON.stringify(formats)});\n` +
    `export { ${helpers.join(", ")} };\n`;
  const shared = (extra) =>
    `import { ${[...extra, "createCapabilities", ...factories, ...helpers].join(", ")} } from "./shared.js";\n`;

  const node = `${header}import { readFileSync } from "node:fs";
import * as wasmGlue from "${glue}";
${shared([])}
const wasmModule = new WebAssembly.Module(readFileSync(new URL("${asset}", import.meta.url)));
const wasmInstance = new WebAssembly.Instance(wasmModule, { "${glueImport}": wasmGlue });
wasmGlue.__wbg_set_wasm(wasmInstance.exports);

export function init() {}

${body}`;

  const web = `${header}import * as wasmGlue from "${glue}";
${shared(["instantiateWasm"])}
let initialized = false;

export async function init(input) {
  if (initialized) return;
  const url = new URL("${asset}", import.meta.url);
  await instantiateWasm(wasmGlue, "${glueImport}", input, url);
  initialized = true;
}

${body}`;
  return { node, web };
}

function build() {
  const bindgen = run("wasm-bindgen", ["--version"], true);
  if (bindgen !== "wasm-bindgen 0.2.129") {
    throw new Error(`Expected wasm-bindgen 0.2.129 (matching Cargo.lock), found ${bindgen}`);
  }
  const target = resolve(root, process.env.CARGO_TARGET_DIR || "target");
  for (const entry of ENTRIES) {
    const { name, features } = entry;
    console.log(`\nironmark/${name}: --features ${features}`);
    run("cargo", [
      "build",
      "-p",
      "ironmark-wasm",
      "--no-default-features",
      "--features",
      features,
      "--profile",
      "release-wasm",
      "--target",
      "wasm32-unknown-unknown",
    ]);
    const outDir = join(dir, `pkg-${name}`);
    mkdirSync(outDir, { recursive: true });
    run("wasm-bindgen", [
      "--target",
      "bundler",
      "--out-dir",
      outDir,
      "--out-name",
      `ironmark_${name}`,
      join(target, "wasm32-unknown-unknown/release-wasm/ironmark.wasm"),
    ]);
    const artifact = join(outDir, `ironmark_${name}_bg.wasm`);
    run("wasm-opt", ["--enable-bulk-memory", "-O3", artifact, "-o", artifact]);
    const { node, web } = entrySources(entry);
    writeFileSync(join(dir, `${name}-node.js`), node);
    writeFileSync(join(dir, `${name}-web.js`), web);
    console.log(`ironmark/${name}: ${readFileSync(artifact).length} WASM bytes`);
  }
}

try {
  build();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
