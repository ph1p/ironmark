import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const dir = dirname(fileURLToPath(import.meta.url));
const wasmPath = join(dir, "pkg", "ironmark_bg.wasm");
const outPath = join(dir, "node.js");

let wasmBytes;
try {
  wasmBytes = readFileSync(wasmPath);
} catch (cause) {
  throw new Error(
    `Cannot read WASM artifact ${wasmPath}; build it before generating the Node entry`,
    {
      cause,
    },
  );
}

const source = `// Generated by wasm/build.mjs — do not edit
import { readFileSync } from "node:fs";
import * as wasmGlue from "./pkg/ironmark_bg.js";
import {
  createParseMarkdown,
  createRenderHtml,
  createRenderMarkdown,
  createRenderAnsiTerminal,
  createParseHtmlToAst,
  createHtmlToMarkdown,
  getCapabilities,
  getAstSchemaVersion,
  getDefaultOptions,
  getPresets,
  extractHeadings,
  summarizeAst,
} from "./shared.js";

const wasmBytes = readFileSync(new URL("./pkg/ironmark_bg.wasm", import.meta.url));
const wasmModule = new WebAssembly.Module(wasmBytes);
const wasmInstance = new WebAssembly.Instance(wasmModule, { "./ironmark_bg.js": wasmGlue });

wasmGlue.__wbg_set_wasm(wasmInstance.exports);

export function init() {}

export const parseMarkdown = createParseMarkdown(wasmGlue.parseToAst);
export const renderHtml = createRenderHtml(wasmGlue.parse, wasmGlue.parseDefault);
export const renderMarkdown = createRenderMarkdown(wasmGlue.renderMarkdown);
export const renderAnsiTerminal = createRenderAnsiTerminal(wasmGlue.renderAnsi);
export const parseHtmlToAst = createParseHtmlToAst(wasmGlue.parseHtmlToAst);
export const htmlToMarkdown = createHtmlToMarkdown(wasmGlue.htmlToMarkdown);

export { getCapabilities, getAstSchemaVersion, getDefaultOptions, getPresets };
export { extractHeadings, summarizeAst };
`;

writeFileSync(outPath, source);
console.log(
  `Generated ${outPath} (${wasmBytes.length} WASM bytes, loaded from pkg/ironmark_bg.wasm)`,
);
