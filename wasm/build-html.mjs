// Prototype only: separate HTML artifact, no npm export or publish-allowlist changes.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { delimiter, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const root = dirname(dir);
const env = {
  ...process.env,
  PATH: [join(root, ".wasm-tools/bin"), join(homedir(), ".cargo/bin"), process.env.PATH]
    .filter(Boolean)
    .join(delimiter),
};

function run(command, args, capture = false) {
  const result = spawnSync(command, args, {
    cwd: root,
    env,
    encoding: "utf8",
    stdio: capture ? "pipe" : "inherit",
  });
  if (result.error) throw new Error(`Cannot run ${command}`, { cause: result.error });
  if (result.status !== 0) {
    throw new Error(
      `${command} ${args.join(" ")} failed (exit ${result.status}): ${result.stderr ?? ""}`,
    );
  }
  return result.stdout?.trim();
}

const bindgen = run("wasm-bindgen", ["--version"], true);
if (bindgen !== "wasm-bindgen 0.2.129") {
  throw new Error(`Expected wasm-bindgen 0.2.129 (matching Cargo.lock), found ${bindgen}`);
}
console.log(`HTML-only prototype: ${bindgen}; ${run("wasm-opt", ["--version"], true)}`);
run("cargo", [
  "build",
  "-p",
  "ironmark-wasm",
  "--no-default-features",
  "--features",
  "html-only",
  "--profile",
  "release-wasm",
  "--target",
  "wasm32-unknown-unknown",
]);
const target = resolve(root, process.env.CARGO_TARGET_DIR || "target");
const outDir = join(dir, "pkg-html");
mkdirSync(outDir, { recursive: true });
run("wasm-bindgen", [
  "--target",
  "bundler",
  "--out-dir",
  outDir,
  "--out-name",
  "ironmark_html",
  join(target, "wasm32-unknown-unknown/release-wasm/ironmark.wasm"),
]);
const artifact = join(outDir, "ironmark_html_bg.wasm");
run("wasm-opt", ["--enable-bulk-memory", "-O3", artifact, "-o", artifact]);
const bytes = readFileSync(artifact);
const source = `// Generated by wasm/build-html.mjs — prototype, not a published entry
import { readFileSync } from "node:fs";
import * as wasmGlue from "./pkg-html/ironmark_html_bg.js";
import { createRenderHtml } from "./shared.js";

const wasmBytes = readFileSync(new URL("./pkg-html/ironmark_html_bg.wasm", import.meta.url));
const wasmModule = new WebAssembly.Module(wasmBytes);
const wasmInstance = new WebAssembly.Instance(wasmModule, { "./ironmark_html_bg.js": wasmGlue });
wasmGlue.__wbg_set_wasm(wasmInstance.exports);

export function init() {}
export const renderHtml = createRenderHtml(wasmGlue.parse, wasmGlue.parseDefault);
`;
const nodePath = join(dir, "html-node.js");
writeFileSync(nodePath, source);
console.log(`Generated ${nodePath} (${bytes.length} HTML-only WASM bytes)`);
