// Opt-in experiment only. Never replaces the speed-first full or HTML-only outputs.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { delimiter, dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const root = dirname(dir);
const env = {
  ...process.env,
  PATH: [join(root, ".wasm-tools/bin"), join(homedir(), ".cargo/bin"), process.env.PATH]
    .filter(Boolean)
    .join(delimiter),
};

export function parseArgs(args) {
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    throw new Error("Unsupported arguments. Usage: node wasm/build-size.mjs [--check]");
  }
  return { check: args.length === 1 };
}

export function checkBindgenVersion(version) {
  if (version !== "wasm-bindgen 0.2.129") {
    throw new Error(`Expected wasm-bindgen 0.2.129 (matching Cargo.lock), found ${version}`);
  }
}

export function runChecked(command, args, { capture = false } = {}) {
  const result = spawnSync(command, args, {
    cwd: root,
    env,
    encoding: "utf8",
    stdio: capture ? "pipe" : "inherit",
  });
  if (result.error) throw new Error(`Cannot run ${command}`, { cause: result.error });
  if (result.status !== 0) {
    throw new Error(
      `${command} ${args.join(" ")} failed (exit ${result.status}, signal ${result.signal}): ${result.stderr ?? ""}`,
    );
  }
  return result.stdout?.trim();
}

async function build(args) {
  const options = parseArgs(args);
  const bindgen = runChecked("wasm-bindgen", ["--version"], { capture: true });
  checkBindgenVersion(bindgen);
  const optimizer = runChecked("wasm-opt", ["--version"], { capture: true });
  console.log(`Size experiment: ${bindgen}; ${optimizer}; wasm-opt --enable-bulk-memory -O3`);
  const templates = {};
  for (const [kind, file] of [
    ["full", "node.js"],
    ["html", "html-node.js"],
  ]) {
    try {
      templates[kind] = readFileSync(join(dir, file), "utf8");
    } catch (cause) {
      throw new Error("Build speed references first: pnpm build && node wasm/build-html.mjs", {
        cause,
      });
    }
  }
  const target = resolve(root, process.env.CARGO_TARGET_DIR || "target");
  const variants = [];
  for (const [level, profile] of [
    ["s", "release-wasm-size"],
    ["z", "release-wasm-size-z"],
  ]) {
    for (const kind of ["full", "html"]) {
      const id = `${kind}-${level}`;
      const features = kind === "full" ? "full" : "html-only";
      const command = [
        "build",
        "-p",
        "ironmark-wasm",
        "--no-default-features",
        "--features",
        features,
        "--profile",
        profile,
        "--target",
        "wasm32-unknown-unknown",
      ];
      console.log(`\n${id}: cargo ${command.join(" ")}`);
      runChecked("cargo", command);
      const outDir = join(dir, "pkg-size", id);
      const name = `ironmark_${kind}_${level}`;
      mkdirSync(outDir, { recursive: true });
      runChecked("wasm-bindgen", [
        "--target",
        "bundler",
        "--out-dir",
        outDir,
        "--out-name",
        name,
        join(target, `wasm32-unknown-unknown/${profile}/ironmark.wasm`),
      ]);
      const artifact = join(outDir, `${name}_bg.wasm`);
      runChecked("wasm-opt", ["--enable-bulk-memory", "-O3", artifact, "-o", artifact]);
      const oldName = kind === "full" ? "ironmark" : "ironmark_html";
      const oldDirectory = kind === "full" ? "pkg" : "pkg-html";
      const oldGlue = `./${oldDirectory}/${oldName}_bg.js`;
      const oldAsset = `./${oldDirectory}/${oldName}_bg.wasm`;
      const oldImport = `./${oldName}_bg.js`;
      let source = templates[kind];
      for (const token of [oldGlue, oldAsset, oldImport]) {
        if (!source.includes(token))
          throw new Error(`Unexpected ${kind} template: missing ${token}`);
      }
      // Reuse the speed wrapper/factories; only generated binding/asset paths change.
      source = source
        .replaceAll(oldGlue, `./pkg-size/${id}/${name}_bg.js`)
        .replaceAll(oldAsset, `./pkg-size/${id}/${name}_bg.wasm`)
        .replaceAll(oldImport, `./${name}_bg.js`)
        .replace(
          /^\/\/ Generated[^\n]*\n/,
          `// Generated by wasm/build-size.mjs — experimental ${id}\n`,
        );
      const entry = join(dir, `size-${id}.js`);
      writeFileSync(entry, source);
      variants.push({
        id,
        kind,
        level,
        features,
        profile,
        artifact,
        entry,
        raw_bytes: readFileSync(artifact).length,
      });
      console.log(`${id} artifact: ${artifact}\n${id} entry: ${entry}`);
    }
  }
  if (options.check) {
    const { runHtmlChecks } = await import("./html-fixtures.mjs");
    const references = {
      full: await import("./node.js"),
      html: await import("./html-node.js"),
    };
    for (const variant of variants) {
      const candidate = await import(pathToFileURL(variant.entry).href);
      const wasmModule = new WebAssembly.Module(readFileSync(variant.artifact));
      const proof = runHtmlChecks(references[variant.kind], candidate, {
        wasmModule,
        htmlOnly: variant.kind === "html",
        fullApi: references.full,
      });
      console.log(`CHECK ${variant.id}: ${JSON.stringify(proof)}; actual ${variant.entry}`);
      variant.checked = proof;
    }
  }
  const reportDir = join(root, "target/plan008");
  mkdirSync(reportDir, { recursive: true });
  writeFileSync(
    join(reportDir, "variants.json"),
    JSON.stringify(
      {
        bindgen,
        optimizer,
        optimizer_flags: ["--enable-bulk-memory", "-O3"],
        variants,
      },
      null,
      2,
    ) + "\n",
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    await build(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
